package org.metabit.platform.support.config.tool;

import picocli.CommandLine.Command;
import picocli.CommandLine.Option;

import java.nio.file.Path;
import java.util.concurrent.Callable;

/**
 * Command to print a generic Kubernetes RBAC template for the Kubernetes storages.
 * <p>
 * The template is broad: it grants read on <em>all</em> ConfigMaps and Secrets in the
 * namespace. It is not least privilege. A generator that limits the rules to the configured
 * resources ({@code resourceNames}) is planned (MLIB-150).
 */
@Command(name = "kubernetes-rbac",
         description = {"Print a generic RBAC template for the Kubernetes sources.",
                        "BROAD: grants read (get, watch) on ALL ConfigMaps and Secrets in the namespace; not least privilege.",
                        "Restrict it with resourceNames to the resources you configured before applying it."})
public class KubernetesRbacCommand implements Callable<Integer>
{
    @Option(names = {"-s", "--schema"}, description = "Ignored; kept for compatibility. Schemas carry no source information.")
    private Path schemaPath;

    @Option(names = {"-n", "--namespace"}, description = "Target namespace.")
    private String namespace = "default";

    @Option(names = {"-a", "--service-account"}, description = "ServiceAccount name.")
    private String serviceAccount = "default";

    @Override
    public Integer call()
    {
        // the Kubernetes storages only GET named resources and watch them by metadata.name; no list.
        System.out.println("# Generated by mConfig Tool");
        System.out.println("# GENERIC TEMPLATE, NOT LEAST PRIVILEGE: grants read on ALL ConfigMaps and Secrets in namespace " + namespace + ".");
        System.out.println("# Add resourceNames for the ConfigMaps and Secrets mConfig is configured to read before applying,");
        System.out.println("# and drop \"secrets\" if none are used.");
        System.out.println("apiVersion: rbac.authorization.k8s.io/v1");
        System.out.println("kind: Role");
        System.out.println("metadata:");
        System.out.println("  namespace: " + namespace);
        System.out.println("  name: mconfig-reader");
        System.out.println("rules:");
        System.out.println("- apiGroups: [\"\"]");
        System.out.println("  resources: [\"configmaps\", \"secrets\"]");
        System.out.println("  verbs: [\"get\", \"watch\"]");
        System.out.println("---");
        System.out.println("apiVersion: rbac.authorization.k8s.io/v1");
        System.out.println("kind: RoleBinding");
        System.out.println("metadata:");
        System.out.println("  namespace: " + namespace);
        System.out.println("  name: mconfig-reader-binding");
        System.out.println("subjects:");
        System.out.println("- kind: ServiceAccount");
        System.out.println("  name: " + serviceAccount);
        System.out.println("  namespace: " + namespace);
        System.out.println("roleRef:");
        System.out.println("  kind: Role");
        System.out.println("  name: mconfig-reader");
        System.out.println("  apiGroup: rbac.authorization.k8s.io");

        return 0;
    }
}
